//! Deterministically generate our own magic multipliers at build time.
use std::{env, fs, path::PathBuf};
fn ray(s: usize, occ: u64, bishop: bool) -> u64 {
    let dirs: &[(i32, i32)] = if bishop {
        &[(1, 1), (1, -1), (-1, 1), (-1, -1)]
    } else {
        &[(1, 0), (-1, 0), (0, 1), (0, -1)]
    };
    let mut out = 0;
    for &(df, dr) in dirs {
        let (mut f, mut r) = (s as i32 % 8 + df, s as i32 / 8 + dr);
        while (0..8).contains(&f) && (0..8).contains(&r) {
            let b = 1u64 << (r * 8 + f);
            out |= b;
            if occ & b != 0 {
                break;
            }
            f += df;
            r += dr;
        }
    }
    out
}
fn next(x: &mut u64) -> u64 {
    *x ^= *x >> 12;
    *x ^= *x << 25;
    *x ^= *x >> 27;
    x.wrapping_mul(2685821657736338717)
}
fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let mut rng = 0x123456789abcdefu64;
    let mut output = String::from("// Generated by build.rs; do not edit.\n");
    for (name, bishop) in [("ROOK", false), ("BISHOP", true)] {
        output.push_str(&format!("pub const {name}: [(u64,u64,u32,usize);64] = [\n"));
        let mut offset = 0;
        for sq in 0..64 {
            let rank = 0xffu64 << (sq / 8 * 8);
            let file = 0x0101010101010101u64 << (sq % 8);
            let edges = ((0xff | 0xff00000000000000) & !rank)
                | ((0x0101010101010101 | 0x8080808080808080) & !file);
            let mask = ray(sq, 0, bishop) & !edges;
            let bits = mask.count_ones();
            let size = 1usize << bits;
            let mut occs = Vec::with_capacity(size);
            let mut attacks = Vec::with_capacity(size);
            let mut sub = 0u64;
            loop {
                occs.push(sub);
                attacks.push(ray(sq, sub, bishop));
                sub = sub.wrapping_sub(mask) & mask;
                if sub == 0 {
                    break;
                }
            }
            let mut used = vec![0u64; size];
            let mut stamps = vec![0u32; size];
            let mut generation = 0u32;
            let magic = loop {
                let m = next(&mut rng) & next(&mut rng) & next(&mut rng);
                if (mask.wrapping_mul(m) & 0xff00000000000000).count_ones() < 6 {
                    continue;
                }
                generation += 1;
                let mut valid = true;
                for i in 0..size {
                    let j = (occs[i].wrapping_mul(m) >> (64 - bits)) as usize;
                    if stamps[j] == generation && used[j] != attacks[i] {
                        valid = false;
                        break;
                    }
                    stamps[j] = generation;
                    used[j] = attacks[i];
                }
                if valid {
                    break m;
                }
            };
            output.push_str(&format!(
                "({mask}u64,{magic}u64,{},{}),\n",
                64 - bits,
                offset
            ));
            offset += size;
        }
        output.push_str("];\n");
        output.push_str(&format!("pub const {name}_SIZE: usize = {offset};\n"));
    }
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("magics.rs"),
        output,
    )
    .unwrap();
}
